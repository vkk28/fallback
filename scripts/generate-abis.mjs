import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const names = ['FallbackFactory', 'FallbackPlan', 'FallbackTestToken'];
for (const name of names) {
  const artifact = JSON.parse(await readFile(new URL(`../contracts/out/${name}.sol/${name}.json`, import.meta.url), 'utf8'));
  if (!artifact.bytecode?.object || artifact.bytecode.object.length < 4) throw new Error(`${name}: missing creation bytecode; run pnpm contracts:build`);
  const checksum = createHash('sha256').update(artifact.bytecode.object).digest('hex');
  const text = `// Generated by pnpm chain:abis from Solidity 0.8.30. Do not edit.\n// Creation bytecode SHA-256 (hex text): ${checksum}\nexport const ${name}Abi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
  await writeFile(new URL(`../packages/chain/src/${name}.ts`, import.meta.url), text);
}
console.log('Generated 3 typed ABIs from compiled contracts');
