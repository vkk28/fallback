import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { createTestIndexer } from 'envio';
import './handlers/events.js';

const source = await readFile('../docs/evidence/local-events.json', 'utf8');
const events = JSON.parse(source, (_, value: unknown) => typeof value === 'object' && value !== null && 'bigint' in value ? BigInt(String(value.bigint)) : value);
const local = JSON.parse(await readFile('../docs/evidence/local-integration.json', 'utf8'));
const id = `31337:${local.plans[0].toLowerCase()}`;
const endBlock = Math.max(...events.map((e: { block: { number: number } }) => e.block.number));
const indexer = createTestIndexer();
await indexer.process({ chains: { 31337: { startBlock: 0, endBlock, simulate: events } } });
const plan = await indexer.Plan.getOrThrow(id);
assert.equal(plan.paid, 450_000_000n);
assert.equal(plan.used, 200_000_000n);
assert.equal(plan.lifecycle, 'Closed');
assert.equal(plan.reserve, 0n);
const shares = await indexer.Supporter.getWhere({ planId: { _eq: id } });
assert.deepEqual(shares.map(s => s.entitlement).sort((a, b) => a < b ? -1 : 1), [33_333_334n, 66_666_666n]);
assert.equal(shares.reduce((n, s) => n + s.claimed, 0n), 100_000_000n);
const payments = await indexer.Installment.getWhere({ planId: { _eq: id } });
assert.equal(payments.length, 3);
const fresh = createTestIndexer();
await fresh.process({ chains: { 31337: { startBlock: 0, endBlock, simulate: events } } });
assert.deepEqual(await fresh.Plan.getOrThrow(id), plan);
const replay = createTestIndexer();
for (const e of await indexer.Plan.getAll()) replay.Plan.set(e);
for (const e of await indexer.Terms.getAll()) replay.Terms.set(e);
for (const e of await indexer.Timeline.getAll()) replay.Timeline.set(e);
for (const e of await indexer.Supporter.getAll()) replay.Supporter.set(e);
for (const e of await indexer.Installment.getAll()) replay.Installment.set(e);
await replay.process({ chains: { 31337: { startBlock: 0, endBlock, simulate: events } } });
assert.deepEqual(await replay.Plan.getOrThrow(id), plan);
await writeFile('../docs/evidence/indexer-verification.json', JSON.stringify({ actualCapturedEvents: events.length, duplicateReplay: 'passed', freshRebuild: 'passed', paid: plan.paid.toString(), used: plan.used.toString(), refunds: shares.map(s => s.entitlement.toString()), runtime: 'Envio createTestIndexer with real captured local receipts; no hosted indexer', observedAt: new Date().toISOString() }, null, 2));
console.log('Envio handlers verified: real event replay, duplicate handling, financial history, exact refunds, and fresh rebuild.');
